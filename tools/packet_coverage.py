#!/usr/bin/env python3
"""Inventory every pinned packet ID and conservatively classify source coverage."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]


def render():
    packets=json.loads((ROOT/'reference/26.3/packets.json').read_text())
    source=(ROOT/'src/Server/Server.php').read_text()
    methods={}
    for state in packets:
        match=re.search(r'private function '+state+r'\([^\n]+\).*?\n    }',source,re.S)
        methods[state]=match.group(0) if match else ''
    emitted=set()
    for path in sorted((ROOT/'src').rglob('*.php')):
        emitted.update(re.findall(r"->send\(\$this->version,\s*'([^']+)'",path.read_text()))
    # Ordinary movement is emitted through a bounded tracker adapter rather
    # than individual literal send calls. Its packet builder names every type.
    tracker = ROOT/'src/Server/Tracking/EntityMovementTracker.php'
    if tracker.is_file():
        emitted.update(re.findall(r"\$this->packet\(\s*'([^']+)'", tracker.read_text()))
    optional={'client_tick_end','debug_subscription_request','pong'}
    ignored_config={'client_information','custom_payload','resource_pack'}
    lines=['# Protocol coverage inventory','',
        'Generated by `python3 tools/packet_coverage.py` from the checksum-pinned official Minecraft Java 26.3 packet report (protocol 777).', '',
        'This is a source inventory, not a parity claim. **Partial handler** means a named dispatch branch exists; its fields and behavior still need vanilla comparison. **Emission reference** means source contains a send call for that packet name; it does not prove every state, variant or ordering. **Unsupported** means no named handler/emission was found. Required unsupported play packets currently reach a silent default branch; configuration/login violations are rejected. Optional telemetry is listed separately and is not counted as gameplay support.', '',
        'Reconfiguration, full item components and many interactions remain unsupported. See issues [#2](https://github.com/lunaboppin/php-minecraft-java-server/issues/2), [#3](https://github.com/lunaboppin/php-minecraft-java-server/issues/3) and the [comparison harness](../tools/parity/README.md).','']
    counts={}
    for state,flows in packets.items():
        for direction,entries in flows.items():
            lines += [f'## {state} / {direction}','','| ID | Packet | Coverage |','| --- | --- | --- |']
            for full,entry in sorted(entries.items(),key=lambda item:item[1]['protocol_id']):
                name=full.removeprefix('minecraft:');status='Unsupported'
                if direction=='clientbound':
                    if name in emitted:status='Emission reference'
                elif state=='configuration' and name in ignored_config:status='Accepted without payload validation / behavior'
                elif re.search(r"(?:case\s+|\$name\s*[!=]==?\s*)'"+re.escape(name)+"'",methods[state]):status='Partial handler'
                elif state=='play' and name in optional:status='Optional telemetry ignored without payload validation'
                counts[status]=counts.get(status,0)+1
                lines.append(f'| {entry["protocol_id"]} | `{name}` | {status} |')
            lines.append('')
    summary=', '.join(f'{n} {status.lower()}' for status,n in sorted(counts.items()))
    lines[4:4]=[f'All **{sum(counts.values())}** reported packet IDs are listed: {summary}.','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output=ROOT/'docs/protocol-coverage.md';contents=render()
    if args.check:
        if not output.is_file() or output.read_text()!=contents:raise SystemExit('Protocol inventory is stale; run python3 tools/packet_coverage.py')
    else:output.write_text(contents)
    print('Protocol inventory covers every pinned packet ID')


if __name__=='__main__':main()
